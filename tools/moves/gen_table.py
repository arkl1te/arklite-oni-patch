#!/usr/bin/python3 -I
"""Writes src/moves_table.h for chat.c's /moves, which looks each row up in the character's live
animation collection (make.sh runs it).

    gen_table.py <Oni_Character_Animation.h> <XML folder> <moves.json> [<package XML folder> <package moves.json>] > src/moves_table.h

The rows, names and shouts are gen_md.py's, so /moves and moves.md agree. Move types and states go
in as the game's numbers: the enums of OniFoxed's Oni_Character_Animation.h (OniGameSource), checked
against enum_numbers.json, OniSplit's names with the numbers retail level0's TRAMs store (+0x15a
type, +0x15e from state; read 2026-11-16). The common rows (every fighter has them) and the game's
own animations on them let /moves leave the stock moves on those rows out.
"""
import json, os, re, sys, xml.etree.ElementTree as ET
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_md

if len(sys.argv) not in (4, 6): sys.exit(__doc__)
HEADER, XML, MOVES = sys.argv[1:4]
PKG_XML, PKG_MOVES = sys.argv[4:6] if len(sys.argv) == 6 else (None, None)

src = open(HEADER).read()
def enum(prefix):
    i = src.find(prefix + "None")
    body = src[i:src.find("}", i)]
    return {n: k for k, n in enumerate(re.findall(prefix + r"(\w+)", body))}
TYPES = enum("ONcAnimType_"); STATES = enum("ONcAnimState_")

md, g = gen_md.make(MOVES, PKG_MOVES)
ROWS, PREREQ, SHOUT, name_of, d = gen_md.ROWS, gen_md.PREREQ, gen_md.SHOUT, g["name_of"], g["d"]

emp = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "enum_numbers.json")))
norm = lambda s: s.replace("_", "").lower()
nt = {norm(k): v for k, v in TYPES.items()}; ns = {norm(k): v for k, v in STATES.items()}
# OniSplit's names that aren't the header's
REN_T = {"RunThrowBackwardKick": "Run_Throw_Behind_Kick", "ThrowBackwardPunch": "Throw_Behind_Punch",
         "ThrowBackwardKick": "Throw_Behind_Kick", "RunThrowBackwardPunch": "Run_Throw_Behind_Punch",
         "Kick3Fw": "Kick3_Forward"}
REN_S = {"SidestepLeftStart": "Sidestep_Left_Start_Long_Name", "SidestepRightStart": "Sidestep_Right_Start_Long_Name"}
def tnum(n):
    v = TYPES[REN_T[n]] if n in REN_T else nt[norm(n)]
    if n in emp["types"]: assert emp["types"][n] == v, n
    return v
def snum(n):
    v = STATES[REN_S[n]] if n in REN_S else ns[norm(n)]
    if n in emp["states"]: assert emp["states"][n] == v, n
    return v

def ascii_(s): return s.replace("×", "x").replace("—", "-")

# inputs every fighter has: the F2 menu's fighters (Shinatama, Hasegawa, the civilians and the
# scientists lack some) and a package's sets. /moves hides them when the move is the game's own and
# has no name
FIGHTERS = ["Konoko", "Griffin", "Muro", "Barabas", "Ninja", "Striker", "Tanker", "Comguy", "Elite", "Red",
            "TCTF SWAT", "TCTF Trooper", "Cop", "Female Cop", "Thug", "Mad Bomber", "Ninjabot", "Sniper"]
if PKG_MOVES: FIGHTERS += list(json.load(open(PKG_MOVES)).keys())
common = None
for who in FIGHTERS:
    if who not in d: sys.exit("missing " + who)
    have = set(g["reachable"](who).keys())
    common = have if common is None else common & have

# the game's own animations on the common rows: every animation of the row's type from one of its
# situations in each class's collections (a superset of what the lookup can pick)
def load(p): return ET.fromstring(open(p, "rb").read().decode("utf-8-sig"))
def trac_of(name):
    for X in (PKG_XML, XML):
        p = os.path.join(X, name + ".xml") if X else None
        if p and os.path.exists(p):
            r = load(p)
            return X, (r.findtext(".//ParentCollection") or "").strip(), [a.text.strip() for a in r.iter("Animation") if a.text and a.text.strip()]
    sys.exit("no " + name)
def tram_info(X, n):
    p = os.path.join(X, n + ".xml")
    if not os.path.exists(p): return None
    lk = load(p).find(".//Lookup")
    return lk.findtext("Type"), [lk.findtext("FromState")] + [s.findtext("FromState") for s in lk.iter("Shortcut")]
stock = set()
for who in d:
    for tr in d[who]["chain"]:
        X, _, anims = trac_of(tr)
        for a in anims:
            ti = tram_info(X, a)
            if not ti: continue
            for inp, alts in ROWS:
                if inp not in common: continue
                for typ, states in alts:
                    if ti[0] == typ and set(ti[1]) & set(states): stock.add(a)

titles = []
for m in re.finditer(r"^## (.+)\n\nAnimation sets: ([^ .,]+)", md, re.M):
    titles.append((m.group(2), m.group(1)))

o = []
w = o.append
w("/* Generated by tools/moves/gen_table.py (make.sh) from the data behind moves.md: don't edit.")
w(" * chat.c's /moves looks every row up in the character's live animation collection. */")
w("")
w("typedef struct { u16 type; u8 states[11]; } MoveAlt;   /* states end at 0 */")
w("typedef struct { const char *input; u16 prereq; u8 common; MoveAlt alt[2]; } MoveRow;")
w("")
w("static const MoveRow g_move_rows[] = {")
POWERUP_AFTER = "Crouch, let go of crouch, kick"
def row_c(inp, alts, com):
    pre = 0
    for typ, _ in alts[:1]:
        if typ in PREREQ: pre = tnum(PREREQ[typ])
    parts = []
    for typ, states in alts:
        assert len(states) <= 10, inp
        parts.append("{ %d, { %s } }" % (tnum(typ), ", ".join(str(snum(s)) for s in states)))
    return '\t{ "%s", %d, %d, { %s } },' % (ascii_(inp), pre, com, ", ".join(parts))
for inp, alts in ROWS:
    assert len(alts) <= 2
    w(row_c(inp, alts, 1 if inp in common else 0) + "   /* " + " / ".join(t + " " + ",".join(s) for t, s in alts) + " */")
    if inp == POWERUP_AFTER:
        w(row_c("Crouch, let go of crouch, Action - regenerates 8% of his health a second up to full",
                [("Powerup", ["Standing"])], 0) + "   /* Powerup Standing */")
w("};")
w("")
w("/* names by animation: Konoko's diary, the super-move shouts, the Oni wiki's Tanker list */")
w("static const char *const g_move_names[][2] = {")
for k in sorted(name_of): w('\t{ "%s", "%s" },' % (k[4:], name_of[k]))
w("};")
w("")
w("/* what a class's super punch or kick sound (ONCC sound names 6, 7) shouts */")
w("static const char *const g_move_shouts[][2] = {")
for k in sorted(SHOUT): w('\t{ "%s", "%s" },' % (k, SHOUT[k]))
w("};")
w("")
w("/* moves.md's section titles by first animation collection (without TRAC and _animations) */")
w("static const char *const g_move_titles[][2] = {")
for k, v in titles: w('\t{ "%s", "%s" },' % (k, v))
w("};")
w("")
w("/* the game's own animations on the common rows: such a row with no name is left out */")
w("static const char *const g_move_stock[] = {")
line = "\t"
for n in sorted(stock):
    t = '"%s", ' % n[4:]
    if len(line) + len(t) > 110: w(line.rstrip()); line = "\t"
    line += t
w(line.rstrip())
w("};")
sys.stdout.write("\n".join(o) + "\n")
print(f"moves_table.h: {len(ROWS) + 1} rows, {len(common)} common, {len(stock)} stock animations, {len(titles)} titles",
      file=sys.stderr)
